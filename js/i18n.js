const SUPPORTED = ["pl", "en", "de"];

function detectLang() {
  // 1) saved user choice
  try {
    const saved = localStorage.getItem("paggini_lang");
    if (saved && SUPPORTED.includes(saved)) return saved;
  } catch (e) {}
  // 2) system / browser language
  const langs = navigator.languages || [navigator.language || "pl"];
  for (const l of langs) {
    const code = l.toLowerCase().slice(0, 2);
    if (SUPPORTED.includes(code)) return code;
  }
  // 3) default
  return "pl";
}

function applyLang(lang) {
  if (!SUPPORTED.includes(lang)) lang = "pl";
  const dict = I18N[lang];
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  const current = document.getElementById("langCurrent");
  if (current) current.textContent = lang.toUpperCase();

  document.querySelectorAll("[data-lang]").forEach((b) => {
    b.classList.toggle("is-active", b.getAttribute("data-lang") === lang);
  });

  try { localStorage.setItem("paggini_lang", lang); } catch (e) {}
  window.PAGGINI_LANG = lang;
}

// expose helper for form messages
function t(key) {
  const lang = window.PAGGINI_LANG || "pl";
  return (I18N[lang] && I18N[lang][key]) || (I18N.pl[key] || key);
}

// initialise immediately (before paint where possible)
applyLang(detectLang());
